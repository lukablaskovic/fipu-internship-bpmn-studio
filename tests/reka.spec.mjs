import assert from 'node:assert/strict';
import { chromium, expect } from '@playwright/test';
import { fileURLToPath } from 'node:url';
const browser = await chromium.launch({ headless: true, ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}) });
const context = await browser.newContext({ viewport: { width: 1440, height: 960 } });
const page = await context.newPage();
const errors = [];
page.on('pageerror', e => errors.push(e.message));
page.on('console', message => { if (message.type() === 'warning' && /missing|requires|invalid|failed/i.test(message.text())) errors.push(message.text()); });
const review = name => fileURLToPath(new URL(`../.impeccable/review/reka-${name}.png`, import.meta.url));
try {
  await page.goto(process.env.STUDIO_URL || 'http://127.0.0.1:5174');
  await expect(page.locator('.bpmn-node')).toHaveCount(31);
  const tabA = page.getByRole('tab', { name: 'Model A Dodjela zadatka', exact: true });
  const tabB = page.getByRole('tab', { name: 'Model B Izravna prijava', exact: true });
  await tabA.focus();
  await tabA.press('ArrowRight');
  await expect(tabB).toBeFocused();
  await expect(tabA).toHaveAttribute('aria-selected', 'true');
  await tabB.press('Enter');
  await expect(page.locator('.bpmn-node')).toHaveCount(21);
  await expect(tabB).toHaveAttribute('aria-selected', 'true');
  await tabA.click();
  await page.getByRole('button', { name: 'Spremanje preferencija u baserow Service Task', exact: true }).click();
  const lane = page.getByRole('combobox', { name: 'Sudionik / staza', exact: true });
  await lane.click();
  await page.getByRole('option', { name: 'Bez staze', exact: true }).click();
  await expect(lane).toHaveText('Bez staze');
  await lane.click();
  await page.getByRole('option', { name: 'Profesor', exact: true }).click();
  await expect(lane).toBeFocused();
  const method = page.getByRole('combobox', { name: 'Metoda', exact: true });
  await method.press('Enter');
  await expect(page.getByRole('option', { name: 'POST', exact: true })).toBeFocused();
  await page.keyboard.press('Home');
  await expect(page.getByRole('option', { name: 'GET', exact: true })).toBeFocused();
  await page.keyboard.press('Enter');
  await expect(method).toHaveText('GET');
  await page.getByRole('combobox', { name: 'Poznata operacija', exact: true }).click();
  await page.getByRole('option', { name: 'Spremi preferencije · POST', exact: true }).click();
  await expect(method).toHaveText('POST');
  await expect(page.getByLabel('Putanja', { exact: true })).toHaveValue('/api/student_preferencije');
  await page.getByLabel('Naziv', { exact: true }).fill('Neprimijenjen naziv');
  await tabB.click();
  const confirmation = page.getByRole('alertdialog');
  await expect(confirmation).toContainText('Model ima nespremljene izmjene');
  await expect(confirmation.getByRole('button', { name: 'Odustani' })).toBeFocused();
  await page.keyboard.press('Shift+Tab');
  assert(await page.evaluate(() => !!document.activeElement.closest('[role=alertdialog]')));
  await page.screenshot({ path: review('confirmation') });
  await page.keyboard.press('Escape');
  await expect(confirmation).toHaveCount(0);
  await expect(tabA).toHaveAttribute('aria-selected', 'true');
  await expect(page.getByLabel('Naziv', { exact: true })).toHaveValue('Neprimijenjen naziv');
  await tabB.click();
  await confirmation.getByRole('button', { name: 'Odbaci izmjene' }).click();
  await expect(tabB).toHaveAttribute('aria-selected', 'true');
  await tabA.click();
  const connect = page.getByRole('button', { name: 'Poveži', exact: true });
  await connect.focus();
  await connect.press('ArrowRight');
  await expect(page.getByRole('button', { name: 'Provjeri model' })).toBeFocused();
  await page.keyboard.press('Enter');
  await expect(page.getByRole('dialog', { name: 'Provjeri model' })).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('button', { name: 'Provjeri model' })).toBeFocused();
  await connect.click();
  await expect(connect).toHaveAttribute('aria-pressed', 'true');
  await page.keyboard.press('Escape');
  await expect(connect).toHaveAttribute('aria-pressed', 'false');
  await page.getByRole('button', { name: 'Prikaži cijeli model', exact: true }).hover();
  await expect(page.getByRole('tooltip')).toContainText('Prikaži cijeli model');
  await page.getByRole('button', { name: 'Ispunjavanje prijavnice User Task', exact: true }).click();
  await page.getByRole('button', { name: 'Svojstva i validacija', exact: true }).first().click();
  await expect(page.getByRole('button', { name: 'Svojstva i validacija', exact: true }).first()).toHaveAttribute('aria-expanded', 'true');
  await expect(page.getByLabel('Svojstva JSON objekt', { exact: true }).first()).toBeVisible();
  await page.getByRole('button', { name: 'Spremanje preferencija u baserow Service Task', exact: true }).click();
  await page.getByRole('combobox', { name: 'Servis', exact: true }).click();
  await page.screenshot({ path: review('select') });
  await page.keyboard.press('Escape');
  await page.setViewportSize({ width: 390, height: 844 });
  const inspector = page.getByRole('dialog', { name: 'Svojstva elementa', exact: true });
  await expect(inspector).toBeVisible();
  const mobileMethod = inspector.getByRole('combobox', { name: 'Metoda', exact: true });
  await mobileMethod.click();
  await page.keyboard.press('Escape');
  await expect(mobileMethod).toBeFocused();
  await expect(inspector).toBeVisible();
  await page.screenshot({ path: review('mobile') });
  await page.keyboard.press('Escape');
  await expect(inspector).toHaveCount(0);
  const opener = page.getByRole('button', { name: 'Otvori elemente' });
  await expect(opener).toBeFocused();
  await opener.click();
  const library = page.getByRole('dialog', { name: 'Elementi procesa' });
  await expect(library).toBeVisible();
  await page.keyboard.press('Shift+Tab');
  assert(await page.evaluate(() => !!document.activeElement.closest('[role=dialog]')));
  await page.keyboard.press('Escape');
  await expect(opener).toBeFocused();
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert.deepEqual(errors, []);
  console.log('Reka tabs, selects, confirmations, toolbar, tooltips, collapsibles and mobile dialog focus checks passed.');
} finally { await browser.close(); }
