import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { chromium, expect } from '@playwright/test';
import { mockModelSource } from './model-source.mjs';

const browser = await chromium.launch({ headless: true, ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}) });
const context = await browser.newContext({ viewport: { width: 1440, height: 960 }, hasTouch: true });
await mockModelSource(context);
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const review = new URL('../.impeccable/review/', import.meta.url);
await mkdir(review, { recursive: true });
try {
  await page.goto(process.env.STUDIO_URL || 'http://127.0.0.1:5174');
  const canvas = page.locator('.fipu-bpmn-canvas');
  const action = page.getByRole('button', { name: 'Poveži element (Sequence Flow)', exact: true });
  const selectTask = () => page.getByRole('button', { name: 'Ispunjavanje prijavnice User Task', exact: true }).click();
  await expect(canvas).toBeVisible();
  await expect(action).toHaveCount(0);
  await selectTask();
  await expect(action).toBeVisible();
  const before = await action.boundingBox();
  await page.getByRole('button', { name: 'Uvećaj', exact: true }).click();
  assert(Math.abs((await action.boundingBox()).width - before.width) < 0.1, 'Action keeps its size when zooming');
  await page.screenshot({ path: fileURLToPath(new URL('connect-desktop.png', review)) });
  await page.getByRole('button', { name: 'Prikaži cijeli model', exact: true }).click();
  const flowCount = await page.locator('.bpmn-flow').count();
  const camera = await canvas.getAttribute('viewBox');
  await action.click();
  await expect(canvas).toHaveClass(/connecting/);
  await expect(action).toHaveCount(0);
  await page.locator('.bpmn-node.selected').press('Enter');
  await expect(page.locator('.bpmn-flow')).toHaveCount(flowCount);
  await page.locator('.bpmn-node[aria-label^="endEvent:"]').first().click();
  await expect(page.locator('.bpmn-flow')).toHaveCount(flowCount + 1);
  await expect(canvas).not.toHaveClass(/connecting/);
  await expect(canvas).toHaveAttribute('viewBox', camera);
  await page.keyboard.press('Control+z');
  await expect(page.locator('.bpmn-flow')).toHaveCount(flowCount);
  await action.focus();
  await action.press('Enter');
  await page.keyboard.press('Escape');
  await expect(action).toBeVisible();
  await expect(page.locator('.bpmn-flow')).toHaveCount(flowCount);
  await page.locator('.bpmn-node[aria-label^="endEvent:"]').first().press('Enter');
  await expect(action).toHaveCount(0);
  await page.locator('.bpmn-flow').first().press('Enter');
  await expect(action).toHaveCount(0);
  await page.locator('.bpmn-node[aria-label^="startEvent:"]').first().press('Enter');
  await expect(action).toBeVisible();
  await page.locator('.bpmn-node[aria-label^="exclusiveGateway:"]').first().press('Enter');
  await expect(action).toBeVisible();
  await selectTask();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Zatvori svojstva', exact: true }).click();
  await expect(action).toBeVisible();
  const mobileButton = await action.boundingBox(), mobileCanvas = await canvas.boundingBox();
  assert(mobileButton.x >= mobileCanvas.x && mobileButton.x + mobileButton.width <= mobileCanvas.x + mobileCanvas.width, 'Action stays inside the mobile canvas');
  await page.screenshot({ path: fileURLToPath(new URL('connect-mobile.png', review)) });
  await action.tap();
  await expect(canvas).toHaveClass(/connecting/);
  await page.keyboard.press('Escape');
  assert.deepEqual(errors, []);
  console.log('Context connection popup, flow creation, undo, cancellation, zoom and mobile checks passed.');
} finally { await browser.close(); }
